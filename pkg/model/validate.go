// ClearValidationCache clears the cached validation metadata for all types.
// Registering a validator on the default registry does this already.
// In normal operation, you should not need to call this function.
func ClearValidationCache() {
	cacheOrderMutex.Lock()
	defer cacheOrderMutex.Unlock()

	cacheGeneration.Add(1)
	validationCache.Clear()
	cacheOrder = nil
}

// ListValidators returns a list of all registered validator names (built-in, custom, and cross-field)
func (r *ValidatorRegistry) ListValidators() []string {
	r.mu.RLock()
	defer r.mu.RUnlock()

	names := make([]string, 0, len(r.validators)+len(r.customFuncs)+len(r.crossFieldFuncs))

	// Add built-in validators
	for name := range r.validators {
		names = append(names, name)
	}

	// Add custom function validators
	for name := range r.customFuncs {
		names = append(names, name)
	}

	// Add cross-field validators
	for name := range r.crossFieldFuncs {
		names = append(names, name)
	}

	return names
}

// ParseValidationTags parses validation tags from a type and returns validation info.
// This function analyzes struct tags and builds the validation rules for efficient validation.
// The returned StructValidation is automatically cached by type for performance.
// Subsequent calls with the same type will return the cached result.
func ParseValidationTags(structType reflect.Type) *StructValidation {
	// Check cache first
	if cached, ok := validationCache.Load(structType); ok {
		return cached.(*StructValidation)
	}

	// Parse validation tags
	generation := cacheGeneration.Load()
	validation := parseValidationTagsUncached(structType)

	// Store in cache with size limit enforcement
	storeInValidationCache(structType, validation, generation)

	return validation
}

// storeInValidationCache stores validation metadata in the cache with size limit enforcement.
func storeInValidationCache(structType reflect.Type, validation *StructValidation, generation uint64) {
	cacheOrderMutex.Lock()
	defer cacheOrderMutex.Unlock()

	if cacheGeneration.Load() != generation {
		return
	}

	maxCacheSize := GetMaxCacheSize()
	if maxCacheSize == 0 {
		// Unlimited caching
		validationCache.Store(structType, validation)
		return
	}

	// Check if cache is full
	if len(cacheOrder) >= maxCacheSize {
		// Remove oldest entry (FIFO)
		oldest := cacheOrder[0]
		validationCache.Delete(oldest)
		cacheOrder = cacheOrder[1:]
	}

	// Add new entry
	validationCache.Store(structType, validation)
	cacheOrder = append(cacheOrder, structType)
}

// parseValidationTagsUncached performs the actual parsing without caching
func parseValidationTagsUncached(typ reflect.Type) *StructValidation {
	validation := &StructValidation{Fields: make([]FieldValidation, 0)}
	validation.collect(typ, typ, make(map[reflect.Type]bool))
	return validation
}

// collect visits every type a value of typ can reach through the validation walk. It works on
// types, not values, so a bad tag under an empty slice still surfaces.
func (v *StructValidation) collect(root, typ reflect.Type, seen map[reflect.Type]bool) {
	if seen[typ] {
		return
	}
	seen[typ] = true

	switch typ.Kind() {
	case reflect.Ptr, reflect.Slice, reflect.Array, reflect.Map:
		v.collect(root, typ.Elem(), seen)
	case reflect.Struct:
		fields, tagErrs := structRules(typ)
		if typ == root {
			v.Fields = fields
		}
		v.TagErrors = append(v.TagErrors, tagErrs...)
		v.holdsRules = v.holdsRules || len(fields) > 0

		for i := 0; i < typ.NumField(); i++ {
			if field := typ.Field(i); isWalked(field) {
				v.collect(root, field.Type, seen)
			}
		}
	}
}

// isWalked reports whether the validation walk enters a field.
func isWalked(field reflect.StructField) bool {
	if field.Anonymous && !field.IsExported() {
		return field.Type.Kind() == reflect.Struct
	}
	return field.IsExported() && getFieldKey(field, FormatJSON) != "-"
}

// structRules parses the validate tags of one struct, reporting tags that cannot run.
func structRules(structType reflect.Type) ([]FieldValidation, []error) {
	fields := make([]FieldValidation, 0)
	var tagErrs []error

	for i := 0; i < structType.NumField(); i++ {
		field := structType.Field(i)

		// Skip unexported fields
		if !field.IsExported() {
			continue
		}

		// Get validation tag
		validateTag := field.Tag.Get("validate")
		if validateTag == "" || validateTag == "-" {
			continue // No validation rules for this field
		}

		// Parse JSON key
		jsonKey := getFieldKey(field, FormatJSON)
		if jsonKey == "-" {
			continue // Field is excluded from JSON
		}

		// Parse validation rules
		rules, err := parseValidationRules(validateTag)
		if err != nil {
			tagErrs = append(tagErrs, fmt.Errorf("%s.%s: invalid validate tag %q: %w", structType, field.Name, validateTag, err))
			continue
		}

		fields = append(fields, FieldValidation{
			FieldName: field.Name,
			JSONKey:   jsonKey,
			Rules:     rules,
		})
	}

	return fields, tagErrs
}

// parseValidationRules parses a validation tag string into ValidationRule structs
// Example: "required,min=5,max=100,email" -> []ValidationRule
func parseValidationRules(tag string) ([]ValidationRule, error) {
	rules := make([]ValidationRule, 0)

	// Split by comma to get individual rules
	for _, part := range strings.Split(tag, ",") {
		rule, err := parseRule(strings.TrimSpace(part), GetDefaultRegistry())
		if err != nil {
			return nil, err
		}
		rules = append(rules, rule)
	}

	return rules, nil
}

// parseRule parses one rule. Format: "min=5" or "required" or "range=1:10"
func parseRule(part string, registry *ValidatorRegistry) (ValidationRule, error) {
	if part == "" {
		return ValidationRule{}, fmt.Errorf("empty rule: remove the stray comma")
	}

	ruleName := part
	params := make(map[string]interface{})

	if equalPos := strings.Index(part, "="); equalPos > 0 {
		// Rule with parameter: "min=5"
		ruleName = part[:equalPos]
		paramValue := part[equalPos+1:]

		// Try to parse parameter as number, fallback to string
		if numVal, err := strconv.ParseFloat(paramValue, 64); err == nil {
			params["value"] = numVal
		} else if intVal, err := strconv.ParseInt(paramValue, 10, 64); err == nil {
			params["value"] = intVal
		} else {
			params["value"] = paramValue
		}
	}

	// Create validator instance
	validator := registry.Create(ruleName, params)
	if validator == nil {
		names := registry.ListValidators()
		sort.Strings(names)
		return ValidationRule{}, fmt.Errorf("unknown validator %q: use one of %s, or register it first",
			ruleName, strings.Join(names, ", "))
	}
	if err := checkRuleParam(ruleName, validator, params); err != nil {
		return ValidationRule{}, err
	}

	return ValidationRule{Name: ruleName, Validator: validator, Parameters: params}, nil
}

// checkRuleParam rejects parameters the built-in factories would replace with their defaults.
// It matches on the validator, not the name, so a custom validator can take over a name.
func checkRuleParam(name string, validator Validator, params map[string]interface{}) error {
	value, isNumber := params["value"].(float64)

	switch validator.(type) {
	case *MinValidator, *MaxValidator:
		if !isNumber || math.IsNaN(value) || math.IsInf(value, 0) {
			return fmt.Errorf("%s needs a number, as in %s=5", name, name)
		}
	case *LengthValidator:
		if !isNumber || value < 0 || value > math.MaxInt32 || value != math.Trunc(value) {
			return fmt.Errorf("%s needs a whole number, as in %s=5", name, name)
		}
	}
	return nil
}

// ValidateValue applies validation rules to a single value.
// This function runs all validation rules and aggregates any errors.
// Use this for simple field validation without cross-field dependencies.
func ValidateValue(fieldName string, value interface{}, rules []ValidationRule) error {
	var errors ErrorList

	for _, rule := range rules {
		if err := rule.Validator.Validate(fieldName, value); err != nil {
			errors.Add(err)
		}
	}

	return errors.AsError()
}

// ValidateValueWithStruct applies validation rules to a single value with access to the full struct.
// This function supports both regular and cross-field validators, making it suitable for
// complex validation scenarios that require access to other fields in the struct.
func ValidateValueWithStruct(fieldName string, value interface{}, rules []ValidationRule, structValue reflect.Value) error {
	var errors ErrorList

	for _, rule := range rules {
		// Check if this is a cross-field validator
		if crossFieldValidator, ok := rule.Validator.(*CrossFieldValidator); ok {
			if err := crossFieldValidator.ValidateWithStruct(fieldName, value, structValue); err != nil {
				errors.Add(err)
			}
		} else {
			// Regular validator
			if err := rule.Validator.Validate(fieldName, value); err != nil {
				errors.Add(err)
			}
		}
	}

	return errors.AsError()
}

// toFloat64 converts various numeric types to float64 for validation purposes
func toFloat64(value interface{}) (float64, error) {
	switch v := value.(type) {
	case float64:
		return v, nil
	case float32:
		return float64(v), nil
	case int:
		return float64(v), nil
	case int8:
		return float64(v), nil
	case int16:
		return float64(v), nil
	case int32:
		return float64(v), nil
	case int64:
		return float64(v), nil
	case uint:
		return float64(v), nil
	case uint8:
		return float64(v), nil
	case uint16:
		return float64(v), nil
	case uint32:
		return float64(v), nil
	case uint64:
		return float64(v), nil
	case string:
		return strconv.ParseFloat(v, 64)
	default:
		return 0, NewParseError("", value, "float64", "cannot convert to numeric value for validation")
	}
}

// toInt converts various numeric types to int for validation purposes
func toInt(value interface{}) (int, error) {
	switch v := value.(type) {
	case int:
		return v, nil
	case int8:
		return int(v), nil
	case int16:
		return int(v), nil
	case int32:
		return int(v), nil
	case int64:
		return int(v), nil
	case uint:
		if v > math.MaxInt64 {
			return 0, NewParseError("", value, "int", "value too large for int")
		}
		return int(v), nil
	case uint8:
		return int(v), nil
	case uint16:
		return int(v), nil
	case uint32:
		return int(v), nil
	case uint64:
		if v > math.MaxInt64 {
			return 0, NewParseError("", value, "int", "value too large for int")
		}
		return int(v), nil
	case float32:
		return int(v), nil
	case float64:
		return int(v), nil
	case string:
		return strconv.Atoi(v)
	default:
		return 0, NewParseError("", value, "int", "cannot convert to integer value for validation")
	}
}
